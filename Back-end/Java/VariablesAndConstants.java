public class VariablesAndConstants {
    static void main() {
        //Variables
        //Puedes declararlas y luego asignarles valor,
        //O declararlas y asignarles valor de una.

        //String name;
        String name = "Roger";

        int age = 34;
        System.out.println(name + age);

        //Constantes
        //Como buena práctica de programación, las constantes,
        //se nombran en mayúsculas
        final String EMAIL = "krocksa@gmail.com";
        System.out.println(EMAIL);
    }
}
