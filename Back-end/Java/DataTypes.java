public class DataTypes {
    public static void main(String[] args) {
        // Tipos de datos primitivos => Son todos los tipos en minúscula

        // Char === Caracter de texto
        char caracter = 'a';

        // Enteros
        int age = 34;

        // Decimales
        double height = 1.75;

        // Booleanos
        boolean bool = true;

        // Otros tipos primitivos numéricos
        // float, long, byte

        // Aunque un String no es un tipo de dato primitivo, por definición,
        // es un tipo de dato muy utilizado, lo adoptaremos como un tipo de dato
        // primitivo,
        // por su uso muy recurente.

        String name = "Roger";
    }
}

