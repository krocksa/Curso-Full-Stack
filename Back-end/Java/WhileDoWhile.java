public class WhileDoWhile {
    public static void main(String[] args) {
        int i = 0;
        // While
        /*
         * while (i < 5) {
         * System.out.println(i);
         * i++;
         * }
         */
        // Do While
        do {
            System.out.println(i);
            i++;
        } while (i < 5);
    }
}
